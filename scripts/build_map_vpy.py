#!/usr/bin/env python3
"""Emit a VapourSynth chain equivalent to build_map.ps1's generated .avs.

Why this exists
---------------
`build_map.ps1` is the authority for cadence *measurement* and still runs
unmodified under pwsh on macOS: it parses the TFM log, decides the repair set,
and writes the deinterlace map. Only the final artefact - an **AviSynth** script -
cannot run here, because AviSynth+ is Windows-only.

So this helper does not re-measure anything. It consumes the *already measured*
outputs of build_map.ps1 and re-expresses the same chain in VapourSynth:

    AviSynth (Windows)                          VapourSynth (macOS)
    ------------------------------------------  ---------------------------------
    LSMASHVideoSource(src).Trim(pad, 0)         core.bs.VideoSource(src) + Trim
    src.TFM(order=-1, pp=0, chroma=true,        core.tivtc.TFM(order=-1, PP=0,
          slow=2)                                     chroma=1, slow=2)
    src.QTGMC(..., FPSDivisor=2)                see --repair (only if needed)
    ReplaceFramesSimple(fm, di, mappings=...)   core.std.FrameEval (proved)
    fm.TDecimate(mode=1, cycle=5,               core.tivtc.TDecimate(mode=1,
          cycleR=1, chroma=true)                      cycle=5, cycleR=1, chroma=1)
    .Trim(start, -end)                          core.std.Trim(start, -end)
    .ConvertBits(10)                            10-bit promotion (ffmpeg then
                                                applies -pix_fmt yuv420p10le)

Parameter parity notes
----------------------
* `order=-1` reads field order from the clip. In VapourSynth TFM that means the
  `_FieldBased` frame property **must be present**, otherwise it raises. We
  deliberately do NOT invent one: a missing property is a measurement problem to
  surface, not a value to guess.
* TFM's `pp=0` (no postprocessing) maps to `PP=0`; `slow=2` maps to `slow=2`.
* The Windows chain keeps 10-bit chroma as-is and lets FFmpeg apply
  `-pix_fmt yuv420p10le`, so this script only guarantees >= 10 bit and leaves
  4:2:0 conversion to the encoder - matching encode_episode.ps1.

Usage
-----
  python scripts/build_map_vpy.py \
      --source /path/stack-master.mov \
      --di-map  /path/full-cadence-di-map.txt \
      --source-pad 0 --trim-start 0 --trim-end 0 \
      --out /path/S01E10-encode.vpy

  # or take the measured values from an existing manifest:
  python scripts/build_map_vpy.py --episode S01E10 --out /path/S01E10-encode.vpy

Exit codes: 0 written, 2 refused (missing measurement / repair set needs a
decision - see --repair).
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from ldcommon import PipelineError, load_episode, load_profile  # noqa: E402

RANGE_RE = re.compile(r"\[(\d+)\s+(\d+)\]")

# build_map.ps1's own documented fallback (see the header it writes into the .avs):
#   "Fallback if QTGMC fails: replace pp=0 with pp=2 and delete the
#    ReplaceFramesSimple lines."
REPAIR_CHOICES = ("none", "qtgmc", "pp2")


def parse_ranges(text: str) -> list[tuple[int, int]]:
    return [(int(a), int(b)) for a, b in RANGE_RE.findall(text)]


def build_source(args) -> str:
    if args.episode:
        ep = load_episode(args.episode)
        return str(ep.path("stack_master"))
    if not args.source:
        raise PipelineError("supply --source or --episode")
    return str(Path(args.source).resolve())


def build_ranges(args) -> list[tuple[int, int]]:
    if args.di_map:
        p = Path(args.di_map)
        if not p.is_file():
            raise PipelineError(f"di-map not found: {p}")
        return parse_ranges(p.read_text(encoding="utf-8", errors="replace"))
    if args.episode:
        ep = load_episode(args.episode)
        p = ep.optional_path("di_map")
        if p and p.is_file():
            return parse_ranges(p.read_text(encoding="utf-8", errors="replace"))
    return []


def render(source: str, pad: int, trim_start: int, trim_end: int,
           ranges: list[tuple[int, int]], repair: str) -> str:
    lines: list[str] = []
    a = lines.append
    a("# Generated by scripts/build_map_vpy.py - VapourSynth port of the .avs")
    a("# that build_map.ps1 writes. Measurement is unchanged: build_map.ps1 still")
    a("# owns the TFM log parse, the repair set and the cadence verdict.")
    a("#")
    a("# Cadence is measured, not guessed.")
    a(f"# source       : {source}")
    a(f"# source pad   : {pad}   (audio capture alignment offset, pre-decimation)")
    a(f"# head trim    : {trim_start}   (post-decimation 23.976 output frames)")
    a(f"# tail trim    : {trim_end}")
    a(f"# repair set   : {len(ranges)} range(s) {ranges if ranges else ''}")
    a("")
    a("import vapoursynth as vs")
    a("")
    a("core = vs.core")
    a(f"SOURCE = {source!r}")
    a(f"SOURCE_PAD = {pad}")
    a(f"TRIM_START = {trim_start}")
    a(f"TRIM_END = {trim_end}")
    a(f"REPAIR_RANGES = {ranges!r}")
    a("")
    a("# --- source -------------------------------------------------------------")
    a("# AviSynth: LSMASHVideoSource(SOURCE).Trim(SOURCE_PAD, 0)")
    a("# bestsource is the sanctioned macOS reader (macOS runbook: LSMASHSource")
    a("# has no VS-mac use here).")
    a("src = core.bs.VideoSource(SOURCE)")
    a("src = core.std.Trim(src, SOURCE_PAD, None)")
    a("# The master reports _FieldBased=0 (measured); TFM(order=-1) needs a real")
    a("# field order. The cadence LOG was generated with _FieldBased=2, so the")
    a("# encode chain must use the same value or TFM would decide differently")
    a("# from the log whose repair map it is following.")
    a("src = core.std.SetFrameProps(src, _FieldBased=2)")
    a("")

    if ranges and repair == "none":
        raise PipelineError(
            f"{len(ranges)} repair range(s) were measured {ranges}, so a "
            "deinterlace stage is required. Pass --repair qtgmc (mapped from "
            "Swap Folder/plugins/QTGMC.avsi) or --repair pp2 (build_map.ps1's "
            "own documented fallback); do not leave the repair unwritten."
        )

    pp = 2 if (ranges and repair == "pp2") else 0
    a("# --- field match --------------------------------------------------------")
    a("# order=-1 reads _FieldBased (set above). Not invented here.")
    a(f"fm = core.tivtc.TFM(src, order=-1, PP={pp}, chroma=1, slow=2)")
    a("")

    if ranges and repair == "pp2":
        a("# --- repair: build_map.ps1's documented fallback ------------------------")
        a("# \"replace pp=0 with pp=2 and delete the ReplaceFramesSimple lines\" -")
        a("# the generated .avs header's own instruction when QTGMC is unavailable.")
        a("")
    elif ranges:
        a("# --- repair: targeted QTGMC map (ReplaceFramesSimple equivalent) --------")
        a("# Windows: di = src.QTGMC(Preset=\"Slower\", SourceMatch=3, Lossless=2,")
        a("#                      TR2=2, Sharpness=0.2, FPSDivisor=2)")
        a("# Every mapping below is read out of Swap Folder/plugins/QTGMC.avsi:")
        a("#   Preset=\"Slower\" -> QTGMC's OWN default (line 218 \"The default preset")
        a("#        is Slower\" / 285 default(Preset,\"Slower\")), so QTempGaussMC()")
        a("#        defaults stand in for it rather than an invented preset.")
        a("#   SourceMatch=3    -> source_match__iterations=3")
        a("#   Lossless=2       -> lossless__mode=PRESHARPEN; QTGMC.avsi:900 applies")
        a("#        QTGMC_MakeLossless *before* resharpen/final temporal smooth (its")
        a("#        own comment calls this not-true-lossless), i.e. the pre-sharpen")
        a("#        slot. Mode 1 (true) is the *post*-smooth slot at :961.")
        a("#   TR2=2            -> final__tr=2; QTGMC.avsi:943-946 maps TR2 to")
        a("#        MDegrain1/2/3, i.e. the final-stage degrain radius.")
        a("#   Sharpness=0.2    -> sharpen__strength=0.2. DELTA: QTGMC scales this")
        a("#        internally via sharpAdj (TR1/TR2 dependent); that scaling is not")
        a("#        replicated, so effective sharpness may differ slightly.")
        a("#   FPSDivisor=2     -> QTGMC.avsi:1002 SelectEvery(FPSDivisor, 0):")
        a("#        bob to double rate, then drop alternate frames, phase 0.")
        a("from vsdeinterlace import QTempGaussMC")
        a("di = QTempGaussMC(")
        a("    source_match__iterations=3,")
        a("    lossless__mode=QTempGaussMC.LosslessMode.PRESHARPEN,")
        a("    final__tr=2,")
        a("    sharpen__strength=0.2,")
        a(").deinterlace(src)                       # tff inferred from _FieldBased")
        a("di = core.std.SelectEvery(di, 2, 0)      # FPSDivisor=2, phase 0")
        a("assert di.num_frames == fm.num_frames, (di.num_frames, fm.num_frames)")
        a("assert (di.fps_num, di.fps_den) == (fm.fps_num, fm.fps_den), \\")
        a("       (di.fps_num, di.fps_den, fm.fps_num, fm.fps_den)")
        a("")
        a("# ReplaceFramesSimple equivalent: 1:1 rate/count, pads only.")
        a("REPAIR = frozenset(n for lo, hi in REPAIR_RANGES for n in range(lo, hi + 1))")
        a("fm_raw = fm")
        a("fm = core.std.FrameEval(fm_raw, lambda n, f=None: di if n in REPAIR else fm_raw)")
        a("")
    else:
        a("# --- repair (no ranges measured; nothing to replace) ------------------")
        a("")
    a("# --- decimation ---------------------------------------------------------")
    a("# AviSynth: fm.TDecimate(mode=1, cycle=5, cycleR=1, chroma=true)")
    a("out = core.tivtc.TDecimate(fm, mode=1, cycle=5, cycleR=1, chroma=1)")
    a("")
    a("# --- trims (post-decimation 23.976 output frames) -----------------------")
    a("# AviSynth Trim(start, 0) == keep to end; Trim(start, -N) == N from end.")
    if trim_end > 0:
        # VapourSynth's std.Trim rejects AviSynth-style negative-from-end indices
        # (it raises "invalid last frame specified"). AviSynth treats -1 as the
        # last frame, so -N maps to the absolute index (num_frames - N). The
        # resulting frame count is verified later by the video.frames / QC gate.
        a("out = core.std.Trim(out, TRIM_START, out.num_frames - TRIM_END)")
    else:
        a("out = core.std.Trim(out, TRIM_START, None)")
    a("")
    a("# --- 10-bit (AviSynth ConvertBits(10)) ----------------------------------")
    a("# Keeps the source chroma subsampling; FFmpeg applies -pix_fmt yuv420p10le")
    a("# exactly as encode_episode.ps1 does on Windows.")
    a("_f = out.format")
    a("if _f.sample_type == vs.INTEGER and _f.bits_per_sample < 10:")
    a("    _tgt = core.query_video_format(_f.color_family, vs.INTEGER, 10,")
    a("                                   _f.subsampling_w, _f.subsampling_h)")
    a("    out = core.resize.Bicubic(out, format=_tgt)")
    a("")
    a("out.set_output()")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", help="stack master (.mov)")
    ap.add_argument("--di-map", help="deinterlace map written by build_map.ps1")
    ap.add_argument("--episode", help="read source/di-map/pad/trims from the manifest")
    ap.add_argument("--source-pad", type=int, default=None,
                    help="audio capture alignment offset (audio.pad_frames)")
    ap.add_argument("--trim-start", type=int, default=None,
                    help="measured head trim (video.head_trim, output frames)")
    ap.add_argument("--trim-end", type=int, default=None,
                    help="measured tail trim (video.tail_trim, 0 if none)")
    ap.add_argument("--out", required=True, help=".vpy to write")
    ap.add_argument("--repair", choices=REPAIR_CHOICES, default="none",
                    help="what to do when a repair set exists: 'qtgmc' (mapped "
                         "from Swap Folder/plugins/QTGMC.avsi), 'pp2' "
                         "(build_map.ps1's documented fallback), or 'none' "
                         "(default: refuse and require a decision)")
    ap.add_argument("--dry-run", action="store_true", help="print, do not write")
    args = ap.parse_args()

    source = build_source(args)
    ranges = build_ranges(args)

    pad = args.source_pad
    t0 = args.trim_start
    t1 = args.trim_end
    if args.episode:
        ep = load_episode(args.episode)
        pad = ep.data.get("audio", {}).get("pad_frames") if pad is None else pad
        t0 = ep.data.get("video", {}).get("head_trim") if t0 is None else t0
        t1 = ep.data.get("video", {}).get("tail_trim") if t1 is None else t1
    for name, val in (("audio.pad_frames", pad), ("video.head_trim", t0),
                      ("video.tail_trim", t1)):
        if val is None:
            raise PipelineError(
                f"{name} is not measured - measure it and record it; never guess")

    text = render(source, int(pad), int(t0), int(t1), ranges, args.repair)

    out = Path(args.out)
    print(f"source      : {source}")
    print(f"pad/trim    : pad={pad} head={t0} tail={t1}")
    print(f"repair set  : {len(ranges)} range(s)")
    if args.dry_run:
        print(text)
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.exists():
        raise PipelineError(f"refusing to overwrite existing file: {out}")
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    print("Chain: source -> Trim(pad) -> TFM(PP=0) -> TDecimate(mode=1) "
          "-> Trim(head,tail) -> 10-bit")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except PipelineError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        raise SystemExit(2)
