"""Video-origin stretches inside a telecined film programme, delivered at one constant 23.976p.

Film (3:2 telecine) is decimated 5→4 by TDecimate and is exact at 23.976p. Video-origin stretches (effects
composited on video, titles, native 29.97 inserts) carry a new moment in every field; plain decimation keeps a
29.97 sample stream and drops one frame in five, a visible hitch. Owner decision 2026-11-22: the delivery stays
one constant 23.976p, and each video stretch gets one of two treatments, chosen per stretch:

``nearest`` (default)
    Interlaced video is bobbed to 59.94p (every field a frame) and, for output frame ``s`` of each 5-frame source
    cycle, the bob frame closest in time to the 23.976 grid is taken: offsets 0, 2, 5, 7 of every 10. Every frame
    is a real deinterlaced frame (no synthesis, grain as captured), and motion is at most half a field (≈8 ms) off
    the even grid, alternating, instead of a 33 ms skip every fifth frame. Native-progressive 29.97 stretches take
    source frames 0, 1, 2, 4 of every 5 (the nearest real frames; a 30→24 conversion cannot avoid one skip).

``interpolate`` (operator choice)
    The same 59.94p (or 29.97p) frames, with the in-between output frames generated by motion-compensated
    interpolation (MVTools FlowFPS) so motion is perfectly even. Half the frames are synthesised; effects shots
    (beams, explosions, starfields, transparency) are where this can warp, and it smooths grain, hence opt-in.

A stretch whose *main picture* is still a film plate (model photography telecined, with only a video-rate overlay
added on top) is left as film: field matching recovers the plate's real film frames and only the overlay's combing
is repaired. That is detected from same-parity field repeats: telecine repeats two of every ten fields, so in such
a stretch two field differences per cycle are far below the rest; true 60i motion has no repeats.

Both treatments produce exactly 4 frames per 5-frame source cycle, the same as decimation, so frame numbers, PAD
maps, trims, audio sync and subtitles are untouched. This module is pure: classification, segments, treatment map.
"""
from __future__ import annotations

import statistics
from dataclasses import dataclass

from fstk.media.cadence import TFM_MI

CYCLE = 5            # source frames per telecine cycle (4 output frames)
OUT_PER_CYCLE = 4
MIN_SEGMENT_CYCLES = 6            # 1 s: shorter stretches stay film (the targeted combing repair covers them)
NATIVE_30P_MAX_ACTIVITY = 0.12    # share of non-"c" matches in a window that still counts as having no telecine
NATIVE_30P_WINDOW = 60

FILM = "film"
VIDEO_I = "video-interlaced"
VIDEO_P = "video-progressive"

NEAREST = "nearest"
INTERPOLATE = "interpolate"
TREATMENTS = (NEAREST, INTERPOLATE)

#: bob (59.94p) frames taken per 10 for output slots 0..3 (times 0, 2.5, 5, 7.5 → nearest real field)
BOB_NEAREST = (0, 2, 5, 7)
#: source (29.97p) frames taken per 5 for output slots 0..3 (times 0, 1.25, 2.5, 3.75)
PROG_NEAREST = (0, 1, 2, 4)

#: film-plate test: the smallest same-parity field difference in a 10-field cycle against the cycle median
PLATE_REPEAT_RATIO = 0.35
PLATE_MIN_CYCLES_SHARE = 0.6      # share of moving cycles that must show a telecine field repeat
STATIC_DIFF = 0.002               # absolute floor: a cycle median below this has no motion to judge
MOTION_OVER_NOISE = 3.0           # a cycle is informative only when its median is this far above the noise floor


@dataclass(frozen=True)
class Segment:
    kind: str
    first_cycle: int            # inclusive, in source telecine cycles (TFM-log / post-pad frame space)
    end_cycle: int              # exclusive
    plate: bool = False         # a film plate under a video overlay: treated as film
    treatment: str = NEAREST

    @property
    def source_frames(self) -> tuple[int, int]:
        return self.first_cycle * CYCLE, self.end_cycle * CYCLE

    @property
    def output_frames(self) -> tuple[int, int]:
        """Untrimmed decimated output frame range [a, b) this stretch occupies."""
        return self.first_cycle * OUT_PER_CYCLE, self.end_cycle * OUT_PER_CYCLE

    @property
    def seconds(self) -> float:
        return (self.end_cycle - self.first_cycle) * CYCLE * 1001 / 30000

    @property
    def active(self) -> bool:
        """True when this stretch is converted (not left to film decimation)."""
        return self.kind != FILM and not self.plate

    def as_dict(self) -> dict:
        return {"kind": self.kind, "first_cycle": self.first_cycle, "end_cycle": self.end_cycle,
                "source_frames": list(self.source_frames), "output_frames": list(self.output_frames),
                "seconds": round(self.seconds, 3), "plate": self.plate, "treatment": self.treatment,
                "active": self.active}

    @classmethod
    def from_dict(cls, d: dict) -> Segment:
        return cls(d["kind"], int(d["first_cycle"]), int(d["end_cycle"]), bool(d.get("plate", False)),
                   str(d.get("treatment", NEAREST)))


def classify_cycles(rows: list[dict]) -> list[str]:
    """One label per whole telecine cycle of the TFM log: film | video-interlaced | video-progressive."""
    mics = [int(r["mic"]) for r in rows]
    codes = [str(r["match_code"]).lower() for r in rows]
    n_cycles = len(rows) // CYCLE
    labels = []
    for c in range(n_cycles):
        a, b = c * CYCLE, (c + 1) * CYCLE
        if sum(m > TFM_MI for m in mics[a:b]) >= 3:            # combed even after field matching: real interlaced motion
            labels.append(VIDEO_I)
            continue
        lo, hi = max(0, a - NATIVE_30P_WINDOW // 2), min(len(rows), b + NATIVE_30P_WINDOW // 2)
        window = codes[lo:hi]
        activity = sum(code != "c" for code in window) / max(len(window), 1)
        labels.append(VIDEO_P if activity <= NATIVE_30P_MAX_ACTIVITY and len(window) >= NATIVE_30P_WINDOW // 2 else FILM)
    return labels


def plan_segments(labels: list[str], *, min_cycles: int = MIN_SEGMENT_CYCLES) -> list[Segment]:
    """Runs of labels → segments; a non-film run shorter than ``min_cycles`` stays film."""
    runs: list[list] = []
    for i, lab in enumerate(labels):
        if runs and runs[-1][0] == lab:
            runs[-1][2] = i + 1
        else:
            runs.append([lab, i, i + 1])
    out: list[Segment] = []
    for lab, a, b in runs:
        if lab != FILM and b - a < min_cycles:
            lab = FILM
        if out and out[-1].kind == lab and out[-1].end_cycle == a:
            out[-1] = Segment(lab, out[-1].first_cycle, b)
        else:
            out.append(Segment(lab, a, b))
    return out


def film_plate_verdict(field_diffs: list[float]) -> dict:
    """Is a stretch's main picture a telecined film plate?

    ``field_diffs[k]`` is the mean absolute difference (0..1) between field ``k`` and field ``k+2`` of the stretch
    (same parity), starting on a cycle boundary. Telecine repeats one field of each parity per 10 fields, so on
    moving film the minimum of each 10-field window sits far below the median; true 60i motion has no repeats.
    """
    cycles = len(field_diffs) // 10
    if cycles == 0:
        return {"plate": False, "informative_cycles": 0, "repeat_cycles": 0, "reason": "too short to judge"}
    # Noise floor: the 10th percentile of all differences. On moving film that is the repeated fields
    # themselves (grain/capture noise only); a cycle whose median is not well above it has no motion to judge.
    noise = sorted(field_diffs)[len(field_diffs) // 10]
    phases, informative = [], 0
    for c in range(cycles):
        w = field_diffs[c * 10:(c + 1) * 10]
        med = statistics.median(w)
        if med < max(STATIC_DIFF, MOTION_OVER_NOISE * noise):
            continue
        informative += 1
        lo = min(w)
        if lo / med < PLATE_REPEAT_RATIO:
            phases.append(w.index(lo))
    if informative == 0:
        return {"plate": False, "informative_cycles": 0, "repeat_cycles": 0, "reason": "no cycle with a repeat-sized gap below its motion: true video motion or static"}
    # The repeat's position moves at every cadence break (edits on the film), so only the share of moving cycles
    # that show a repeat is judged, not a single phase (measured on the S01E20 master: film shots 0.16–0.32,
    # repeats in 43 of 65 moving cycles over a teaser that also holds non-repeating material).
    plate = len(phases) / informative >= PLATE_MIN_CYCLES_SHARE
    return {"plate": plate, "informative_cycles": informative, "repeat_cycles": len(phases),
            "noise_floor": round(noise, 6),
            "reason": ("film plate: telecine field repeats in most moving cycles" if plate
                       else "true video motion: no stable field repeats")}


def apply_choices(segments: list[Segment], choices: dict | None) -> list[Segment]:
    """Apply the operator's per-stretch treatment (keyed by first_cycle as a string) to active stretches."""
    out = []
    for s in segments:
        t = (choices or {}).get(str(s.first_cycle), s.treatment)
        if t not in TREATMENTS:
            raise ValueError(f"unknown treatment {t!r} for the stretch at cycle {s.first_cycle}")
        out.append(Segment(s.kind, s.first_cycle, s.end_cycle, s.plate, t if s.active else NEAREST))
    return out


def cycle_treatments(segments: list[Segment]) -> dict[int, str]:
    """cycle → code for the IVTC script: ``NI`` / ``NP`` (nearest, interlaced / progressive), ``II`` / ``IP``."""
    m: dict[int, str] = {}
    for s in segments:
        if not s.active:
            continue
        code = ("N" if s.treatment == NEAREST else "I") + ("I" if s.kind == VIDEO_I else "P")
        for c in range(s.first_cycle, s.end_cycle):
            m[c] = code
    return m


def summary(segments: list[Segment]) -> dict:
    active = [s for s in segments if s.active]
    plates = [s for s in segments if s.kind != FILM and s.plate]
    return {"segments": [s.as_dict() for s in segments if s.kind != FILM],
            "video_segments": len(active), "video_seconds": round(sum(s.seconds for s in active), 2),
            "plate_segments": len(plates), "plate_seconds": round(sum(s.seconds for s in plates), 2),
            "interpolated_segments": sum(1 for s in active if s.treatment == INTERPOLATE),
            "delivery": "constant 23.976p; same frame count as decimation"}
